/**
 * Двигун для руху king.exe: крива моменту exp(−(|n − n₀|/n₀)⁴) (0x507380; у першій грі ширина 1,5·n₀), решта — як
 * HT2_ENGINE (виміряне телеметрією).
 */
export const HT2_KING_ENGINE: EngineProfile = { ...HT2_ENGINE, torqueWidth: 1 };

/**
 * Рух king.exe (engine/vehicle/kingModel.ts), параметри, яких немає у vehicle.tech:
 * - μ асфальту: таблиця зчеплення за покриттям у king.exe заповнюється не знайденим кодом (за замовчуванням 0,5).
 *   Гальмування ZilR у записі сталося ≈ 7 м/с² (re/notes/ht2/telemetry.md) — у моделі воно впирається в μ·g, тож
 *   μ ≈ 0,71 (гіпотеза до звірки В4);
 * - дощ: за замовчуванням 0,5 → 0,3, тобто ×0,6;
 * - кермо → кут — як у exe, δ = 45°·s з межею 1,5·atan(μ·k·L/v²); k [0x263c] не прочитано — підбір за записами ZilR
 *   2026-10-16 (усі кадри зі сталим кермом, re/notes/ht2/telemetry.md): μ·k·L ≈ 41 при L = 6,54 → k ≈ 8,8. Колишня
 *   підгонка 0,56·|s|^0,7 (з базою 7,22) обрізала кут на малій швидкості до 25° — повертала вдвічі ширше;
 * - крен: у записі ≈ 0,47° на м/с² бічного прискорення до ≈ 3,4° (формула exe — 0,62°/(м/с²) з межею 2,5°).
 */
export const HT2_KING: KingSetup = { mu: 0.71, rain: 0.6, steerK: 8.8, steerScale: 1, steerPower: 1, rollK: 0.0082, rollMax: 0.06 };

/**
 * Гальма для руху king.exe: педаль з клавіші (t + 0,001)/(t + 1) (0x4ff800), сила колеса — 1,5 × навантаження ×
 * педаль у межах μ·N (kingModel.ts). Так сповільнення ≈ 5 м/с² за 0,5 с і ≈ 7 за 1 с — як у записі ZilR (на 0,1 с у
 * записі ≈ 3, тут ≈ 1,3).
 */
export const HT2_KING_BRAKE = { pedal: (t: number) => (t + 0.001) / (t + 1), scale: 1 };

/** Рух king.exe для машини з vehicle.tech (гравець, трафік, суперники, далекобійники); travel — хід підвіски. */
export function kingCar(travel?: readonly number[]): { engine: EngineProfile; brake: typeof HT2_KING_BRAKE; king: KingSetup } {
  return { engine: HT2_KING_ENGINE, brake: HT2_KING_BRAKE, king: { ...HT2_KING, travel } };
}

/** Кут коліс δ → кермо (обернене до δ = 45°·a·|s|^p, HT2_KING). */
export function kingSteer(delta: number): number {
  const k = HT2_KING;
  return Math.sign(delta) * (Math.abs(delta) / (Math.PI / 4) / k.steerScale) ** (1 / k.steerPower);
}

/** Автопілот для машини на русі king.exe: переслідування цілі по дузі з колісною базою base. */
export function kingPilot(ap: AutoPilot, base: number): AutoPilot {
  ap.kinematicBase = base;
  ap.steerFor = kingSteer;
  return ap;
}

