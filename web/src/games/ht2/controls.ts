  neutralBelow: 0.7,
  // Після перемикання оберти йдуть до нових рівномірно: 49,6 → 44,7 → 39,7 → 35,5 → 32,7 по 0,1 с.
  rpmFollow: 50,
  // Вибіг на рівному на 6-й (75…92 км/год): −0,52…−0,66 м/с²; порт із 0,1 першої гри — −0,31…−0,34. З газом
  // ≈ 0,78 на 5-й/6-й порт і оригінал близькі (5-та/55: 1,41 проти 1,45…1,49; 6-та/85: 0,92 проти 0,80…0,88), тож
  // різниця — у гальмуванні двигуном, не в опорі руху. 0,22 → вибіг −0,53…−0,60 (механізм — гіпотеза).
