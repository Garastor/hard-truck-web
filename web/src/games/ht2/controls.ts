/**
 * Межа керма HT2 (частка STEER_TO_WHEEL 0,684 рад): у першій грі кут коліс спадає зі швидкістю (1,04/(1 + 0,056·v)),
 * а в Дальнобойщиках 2 — ні (телеметрія king.exe, ZilR: кривизна 1/R на кермі 0,2 — 0,021 на 45 км/год, 0,023 на 60,
 * тобто кут коліс не менший, ніж на місці, де повне кермо дає R ≈ 8…15 м). Далі поворот обмежує зчеплення
 * шин (бічне до 0,8…1 g). Відгук користувача: «машина більш чутливо реагує на початок повороту, живіша».
 */
// Понад 15 м/с (54 км/год) кут таки спадає: на 75 км/год R 68 м, на 90 — 75 м (кермо 0,2); без спаду порт давав
// 50 і 58 м.
