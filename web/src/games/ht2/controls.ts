  shiftNeutral: 0.1,
  // Холості 4,0 об/с при n₀ = 26,67 (tach_with_max_power ZilR) — 0,15·n₀ (гіпотеза: частка, а не стала).
  idle: 0.15,
  // На рушанні газ наростає тією самою кривою (3,8 км/год — 0,48), без повного газу пробуксовки.
  slipFullGas: false,
  // Автомат перемикає за швидкістю, незалежно від газу (ZilR: вгору на 16 / 29 / 50 / 77 км/год — оберти, звʼязані
  // з колесами, ≈ 50 об/с = 1,875·n₀; вниз на 15,5 / 27,5 / 46,5 / 69,5 км/год — 1,04…1,15·n₀, більше на старших
  // передачах). Поріг вниз — підгонка 0,6 + 0,806 / k по ZilR (гіпотеза; правило оригіналу не розібране).
  shiftByRpm: { up: 1.875, downA: 0.6, downB: 0.806 },
