/** Газ (поле +0xa8 обʼєкта машини) за часом утримання клавіші, с: медіана восьми натискань. */
const GAS: [number, number][] = [
  [0, 0.05], [0.1, 0.185], [0.2, 0.229], [0.3, 0.273], [0.5, 0.382], [0.75, 0.468], [1, 0.528], [1.5, 0.603],
  [2, 0.653], [3, 0.708], [4, 0.739], [6, 0.773], [8, 0.791], [12, 0.809], [20, 0.825],
];
/**
 * З Ctrl («різко») — та сама залежність від часу, але вище (одне чисте натискання; після 5 с — продовжено за
 * формою: 1 − g ≈ (1 − g_звич)^2,3, гіпотеза). Відпустили Ctrl — газ одразу на звичайну криву.
 */
const GAS_SHARP: [number, number][] = [
  [0, 0.05], [0.1, 0.317], [0.2, 0.504], [0.3, 0.6], [0.5, 0.717], [0.75, 0.791], [1, 0.832], [1.5, 0.882],
  [2, 0.909], [3, 0.937], [4, 0.952], [6, 0.967], [8, 0.973], [12, 0.979], [20, 0.984],
];

function table(points: [number, number][], t: number): number {
  if (t <= points[0][0]) return points[0][1];
  for (let i = 1; i < points.length; i++) {
    const [t1, g1] = points[i];
    if (t <= t1) {
      const [t0, g0] = points[i - 1];
      return g0 + ((g1 - g0) * (t - t0)) / (t1 - t0);
    }
  }
  return points[points.length - 1][1];
}

