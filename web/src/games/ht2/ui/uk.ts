const UPPER = new Map(Object.entries(NAMES).map(([ru, uk]) => [ru.toUpperCase(), uk.toUpperCase()]));

/** Текст повідомлення Ms.sch українською (без перекладу — як у файлі). */
export function ukMessage(key: string, text: string): string {
  return MESSAGES[key] ?? text;
}

/** Назва товару чи місця українською. */
export function ukName(name: string): string {
  return NAMES[name] ?? name;
}

/** Назви місць у тексті великими літерами (дорожні написи). */
function places(text: string): string {
  return text.replace(/[А-ЯЁ]+/g, (w) => UPPER.get(w) ?? w);
}

/** Дорожні написи й оголошення mod_*.sch (великими літерами) українською. */
export function ukSign(text: string): string {
  const t = text.trim();
  let m: RegExpExecArray | null;
  if ((m = /^БАЗА (.+?)( НАЛЕВО| НАПРАВО)?,? ЧЕРЕЗ (\d+) М$/.exec(t)))
    return `БАЗА ${places(m[1])}${m[2] === ' НАЛЕВО' ? ' ЛІВОРУЧ' : m[2] ? ' ПРАВОРУЧ' : ''}, ЧЕРЕЗ ${m[3]} М`;
  if ((m = /^ДВИЖЕНИЕ ПО ТРАССЕ (.+) ОТКРЫТО$/.exec(t))) return `РУХ ТРАСОЮ ${places(m[1])} ВІДКРИТО`;
  if ((m = /^ТРАССА (.+) ЗАКРЫТА$/.exec(t))) return `ТРАСУ ${places(m[1])} ЗАКРИТО`;
  if ((m = /^МОСТ НА ТРАССЕ (.+) ВОССТАНОВЛЕН$/.exec(t))) return `МІСТ НА ТРАСІ ${places(m[1])} ВІДНОВЛЕНО`;
  if ((m = /^МОСТ НА ТРАССЕ (.+) НА РЕМОНТЕ$/.exec(t))) return `МІСТ НА ТРАСІ ${places(m[1])} НА РЕМОНТІ`;
  if (t === 'ГЛАВНАЯ ДОРОГА ИЗ ЕЛЬНИНО В БУХТУ ВОССТАНОВЛЕНА') return 'ГОЛОВНУ ДОРОГУ З ЄЛЬНІНО ДО БУХТИ ВІДНОВЛЕНО';
  if (t === 'ГЛАВНАЯ ДОРОГА ИЗ ЕЛЬНИНО В БУХТУ ЗАКРЫТА') return 'ГОЛОВНУ ДОРОГУ З ЄЛЬНІНО ДО БУХТИ ЗАКРИТО';
  return places(t);
}
